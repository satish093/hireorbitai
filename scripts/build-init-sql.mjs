// Build a single consolidated database/init.sql by concatenating every
// per-feature SQL file in dependency order. Operators can then apply the
// whole schema with one `psql -f database/init.sql` instead of running
// every migration by hand.
//
// Run from the repo root:
//   node scripts/build-init-sql.mjs
//
// Files are concatenated VERBATIM. Each block is wrapped in a clear section
// header so when a row from auth_audit_logs makes you want to know which
// migration introduced it, you can `Ctrl-F` the originating filename.
//
// Files deliberately EXCLUDED:
//   - accounts-teardown.sql  — destructive DROP script, not a forward migration
//   - seed-default-admin.sql — no-op stub pointing at `npm run bootstrap:admin`

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// Resolve database/ relative to the repo root, no matter where the script is
// invoked from. scripts/ lives at <root>/scripts; database/ lives at <root>/database.
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(REPO_ROOT);

// Dependency-ordered list. Files within a group are independent of each
// other; groups are ordered so each one's prerequisites are already in scope.
const groups = [
  {
    name: 'Foundation — base schema',
    files: ['schema.sql'],
  },
  {
    name: 'Identity + auth — extends public.users',
    files: [
      'auth-hardening.sql',
      'admin-user-management.sql',
      'user-profile-fields.sql',
      'roles-developer-hr.sql',
      'roles-hierarchy.sql',
      'recruiter-managers.sql',
    ],
  },
  {
    name: 'Feature flags',
    files: ['feature-flags.sql'],
  },
  {
    name: 'User groups + presence + activity',
    files: ['user-groups-and-presence.sql', 'user-activity-tracking.sql'],
  },
  {
    name: 'Consultants (extends public.consultants)',
    files: ['consultant-skills.sql', 'consultant-desired-positions.sql'],
  },
  {
    name: 'Applications + interview pipeline',
    files: ['apply-flow-tables.sql', 'applications-archived-status.sql'],
  },
  {
    name: 'Tasks',
    files: ['tasks.sql', 'tasks-tags.sql'],
  },
  {
    name: 'Messages (DM + presence)',
    files: ['messages.sql'],
  },
  {
    name: 'Jobs — ingestion + drivers',
    files: [
      'job-ingestion.sql',
      'job-ingestion-extra-sources.sql',
      'jobs-extras.sql',
      'jobs-apply-url-backfill.sql',
      'jobs-publisher.sql',
      'jobs-unique-fix.sql',
      'jsearch-source.sql',
      'jsearch-source-expansion.sql',
      'linkedin-source.sql',
      'monster-source.sql',
      'searchapi-source.sql',
      'all-sources-seed.sql',
      'ai-job-search-and-apply.sql',
    ],
  },
  {
    name: 'Training / LMS module',
    files: [
      'training.sql',
      'training-content.sql',
      'training-ai-data.sql',
      'training-i983.sql',
      'training-cybersecurity.sql',
      'training-security.sql',
    ],
  },
];

const PREAMBLE = `-- =============================================================================
-- HireOrbit AI — consolidated database schema
--
-- Single-file alternative to applying every database/*.sql migration by hand.
-- Every block below is the verbatim content of its source file; this file is
-- mechanically generated by scripts/build-init-sql.mjs. To regenerate after
-- editing any individual source file:
--
--   node scripts/build-init-sql.mjs
--
-- Apply to a fresh database:
--
--   createdb hireorbitai
--   psql -d hireorbitai -c 'CREATE EXTENSION IF NOT EXISTS pgcrypto'
--   psql -d hireorbitai -f database/init.sql
--
-- The file is idempotent — re-running on an existing database is safe. Every
-- table uses CREATE TABLE IF NOT EXISTS, every enum is wrapped in a
-- duplicate_object guard, every column add uses ALTER TABLE ... ADD COLUMN
-- IF NOT EXISTS, every index uses CREATE INDEX IF NOT EXISTS.
--
-- For new schema changes AFTER this baseline, use the migration runner under
-- backend/migrations/ — DON'T edit this file directly for new tables.
-- =============================================================================

`;

let out = PREAMBLE;
let total = 0;
const seen = new Set();

for (const group of groups) {
  out += '\n\n-- ###########################################################################\n';
  out += '-- # ' + group.name + '\n';
  out += '-- ###########################################################################\n';

  for (const file of group.files) {
    const path = 'database/' + file;
    let body;
    try {
      body = readFileSync(path, 'utf8');
    } catch {
      console.warn('  ! missing: ' + file + ' (skipped)');
      continue;
    }
    if (seen.has(file)) continue;
    seen.add(file);

    out += '\n\n-- --- ' + file + ' '.padEnd(70 - file.length, '-') + '\n\n';
    out += body.trimEnd() + '\n';
    total++;
  }
}

out += '\n\n-- =============================================================================\n';
out += '-- End of consolidated schema. ' + total + ' source files concatenated.\n';
out += '-- =============================================================================\n';

writeFileSync('database/init.sql', out, 'utf8');
console.log(
  '✓ wrote database/init.sql (' +
    total +
    ' source files, ' +
    Math.round(out.length / 1024) +
    ' KB)',
);
